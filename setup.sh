#!/usr/bin/env bash
#
# stream_lover — one-shot VPS setup for Debian with podman + caddy preinstalled.
#
# What it does:
#   1. Generates (and reuses) secrets in deploy-runtime/.env
#   2. Builds the signaling server image and the web client, both inside throwaway
#      containers (no rustc/node needed on the host)
#   3. Runs coturn (STUN/TURN) and the signaling server with podman
#   4. Publishes the web app + reverse-proxies the API/WebSocket through Caddy (auto-HTTPS)
#
# Usage:
#   ./setup.sh <domain>
#   DOMAIN=stream.example.com ./setup.sh
#
# Re-running is safe on a host set up by this script: it reuses existing secrets and
# replaces the containers in place. It is meant for a fresh, dedicated host: it writes
# /etc/caddy/Caddyfile wholesale. To update only the web UI, use ./deploy-web.sh.

set -euo pipefail

# ---- config -------------------------------------------------------------------
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
RUNTIME_DIR="$REPO_DIR/deploy-runtime"
ENV_FILE="$RUNTIME_DIR/.env"
WEBROOT="${WEBROOT:-/srv/streambree/web}"
CADDYFILE="/etc/caddy/Caddyfile"
SIGNALING_IMAGE="localhost/stream_lover-signaling:latest"
COTURN_IMAGE="docker.io/coturn/coturn:4.6"
NODE_IMAGE="docker.io/library/node:20-bookworm-slim"
DATA_VOLUME="stream_lover_data"

DOMAIN="${1:-${DOMAIN:-}}"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!! \033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mxx \033[0m %s\n' "$*" >&2; exit 1; }

# ---- preflight ----------------------------------------------------------------
[ -n "$DOMAIN" ] || die "Usage: ./setup.sh <domain>   (or set DOMAIN=...). The domain must already point at this VPS."
command -v podman >/dev/null || die "podman not found."
command -v caddy  >/dev/null || die "caddy not found."
[ -f "$REPO_DIR/server/deploy/Dockerfile" ] || die "Run this from the stream_lover repo root."

# Refuse to run where Streambree is already deployed another way, or where Caddy hosts
# other sites: this script would overwrite their routing and start a second API server.
if [ "${FORCE_SETUP:-}" != 1 ]; then
  conflicts=()
  systemctl cat streambree-signaling.service >/dev/null 2>&1 \
    && conflicts+=("systemd service streambree-signaling already runs the API")
  [ -f "$CADDYFILE" ] && grep -qE '^[[:space:]]*import[[:space:]]' "$CADDYFILE" \
    && conflicts+=("$CADDYFILE imports other site configs that would be replaced")
  if [ "${#conflicts[@]}" -gt 0 ]; then
    for c in "${conflicts[@]}"; do warn "$c"; done
    die "This host isn't a fresh setup.sh install. Use ./deploy-web.sh <domain> to update the web UI. Set FORCE_SETUP=1 to run anyway."
  fi
fi

log "Domain: $DOMAIN"
mkdir -p "$RUNTIME_DIR"

# ---- secrets (generate once, reuse forever) -----------------------------------
if [ -f "$ENV_FILE" ]; then
  log "Reusing secrets from $ENV_FILE"
  # shellcheck disable=SC1090
  set -a; . "$ENV_FILE"; set +a
else
  log "Generating fresh secrets"
  JWT_SECRET="$(openssl rand -hex 32)"
  TURN_SECRET="$(openssl rand -hex 32)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh — keep this file secret. Delete it to rotate all secrets.
JWT_SECRET=$JWT_SECRET
TURN_SECRET=$TURN_SECRET
EOF
  umask 022
fi

# ---- coturn config ------------------------------------------------------------
log "Writing coturn config"
cat > "$RUNTIME_DIR/coturn.conf" <<EOF
# Generated by setup.sh — STUN + TURN with REST ephemeral auth.
listening-port=3478
tls-listening-port=5349

use-auth-secret
static-auth-secret=$TURN_SECRET

realm=$DOMAIN

# Relay range — must be open on the VPS firewall (UDP).
min-port=49152
max-port=65535

fingerprint
no-cli
no-loopback-peers
no-multicast-peers
EOF

# ---- build the signaling server image -----------------------------------------
log "Building signaling server image (Rust — first build is slow)"
podman build -t "$SIGNALING_IMAGE" -f "$REPO_DIR/server/deploy/Dockerfile" "$REPO_DIR/server"

# ---- build the web client -----------------------------------------------------
# The client talks to the API at <origin>/api; Caddy strips the /api prefix.
log "Building web client (VITE_SERVER_URL=https://$DOMAIN/api)"
podman run --rm \
  -v "$REPO_DIR/web":/app \
  -w /app \
  -e "VITE_SERVER_URL=https://$DOMAIN/api" \
  "$NODE_IMAGE" \
  bash -c "npm ci && npm run build"

log "Publishing web app to $WEBROOT"
sudo mkdir -p "$WEBROOT"
sudo rm -rf "${WEBROOT:?}/"*
sudo cp -r "$REPO_DIR/web/dist/." "$WEBROOT/"

# ---- run the containers -------------------------------------------------------
log "Starting coturn"
podman run -d --replace --name coturn \
  --network host \
  --restart=always \
  -v "$RUNTIME_DIR/coturn.conf:/etc/coturn/turnserver.conf:ro" \
  "$COTURN_IMAGE"

log "Starting signaling server (listening on 127.0.0.1:8080, fronted by Caddy)"
podman run -d --replace --name stream_lover-signaling \
  --restart=always \
  -p 127.0.0.1:8080:8080 \
  -e BIND_ADDR="0.0.0.0:8080" \
  -e DATABASE_URL="sqlite:/data/stream_lover.db?mode=rwc" \
  -e JWT_SECRET="$JWT_SECRET" \
  -e TURN_SECRET="$TURN_SECRET" \
  -e TURN_URL="turn:$DOMAIN:3478" \
  -e STUN_URL="stun:$DOMAIN:3478" \
  -e TURN_TTL="600" \
  -v "$DATA_VOLUME:/data" \
  "$SIGNALING_IMAGE"

# Best-effort: keep rootless containers running across reboots.
if systemctl --user >/dev/null 2>&1; then
  loginctl enable-linger "$(id -un)" 2>/dev/null || true
  systemctl --user enable podman-restart.service 2>/dev/null || true
fi

# ---- Caddy --------------------------------------------------------------------
log "Configuring Caddy"
sudo tee "$CADDYFILE" >/dev/null <<EOF
$DOMAIN {
    encode zstd gzip

    # API + WebSocket: strip the /api prefix and forward to the signaling server.
    handle_path /api/* {
        reverse_proxy 127.0.0.1:8080
    }

    # Everything else: the single-page web app (client-side routing).
    handle {
        root * $WEBROOT
        try_files {path} /index.html
        file_server
    }
}
EOF

if command -v systemctl >/dev/null && systemctl list-unit-files caddy.service >/dev/null 2>&1; then
  sudo systemctl reload caddy 2>/dev/null || sudo systemctl restart caddy
else
  warn "caddy is not a systemd service here. Reload it yourself, e.g.:  sudo caddy reload --config $CADDYFILE"
fi

# ---- done ---------------------------------------------------------------------
log "Waiting for the signaling server to answer..."
for _ in $(seq 1 15); do
  if curl -fsS "http://127.0.0.1:8080/healthz" >/dev/null 2>&1; then ok=1; break; fi
  sleep 1
done
[ "${ok:-}" = 1 ] && log "Signaling healthy (127.0.0.1:8080/healthz -> ok)" || warn "Signaling didn't answer yet — check: podman logs stream_lover-signaling"

cat <<EOF

$(printf '\033[1;32mDone.\033[0m') stream_lover should be live at: https://$DOMAIN

Open these ports on your VPS firewall / cloud security group:
  - TCP  443           (Caddy: web app + API + wss, auto-HTTPS)
  - UDP+TCP 3478       (STUN/TURN)
  - UDP 49152-65535    (TURN relay range)

Verify:
  curl https://$DOMAIN/api/healthz        # -> ok
  podman ps                               # coturn + stream_lover-signaling running

Notes:
  - Secrets live in deploy-runtime/.env (git-ignored). Delete it to rotate; re-run this script.
  - TURN here is plain (turn:$DOMAIN:3478). For networks that only allow 443, add TLS certs to
    coturn and switch TURN_URL to turns:$DOMAIN:5349 (see server/deploy/README.md).
  - Re-run ./setup.sh anytime to rebuild and redeploy.
EOF
